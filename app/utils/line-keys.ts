/**
 * 本文の行を見分ける印（`ScrapboxEditor` の `v-for` の key）。
 *
 * **行番号は使わない。** 行番号を印にすると、行が増えた・減ったときに、
 * それより下の行の中身が**1つずれた要素へ移る**（1行目に書いた内容が、
 * それまで2行目だった要素に入る）。中身の入れ替わった要素は書き直されるので、
 * 埋め込み（`iframe`）はそこで作り直され、外のページを読み直してしまう。
 * 1行足すたびに、関係のない埋め込みが真っ白から読み直しになる。
 *
 * 書かれたままの行を印にすると、行が増減しても**同じ行は同じ要素のまま**に
 * なり、増えた行だけが差し込まれる。読み直しが起きるのは、ページを開き直した
 * ときと、その行そのものを書き換えたときだけになる。
 */

/**
 * 行ごとの印を作る。同じ文字の行は何行でもあるので、**何番目に出てきたか**を
 * 添えて一意にする（key が重なると、その行から下の描き分けが崩れる）。
 */
export function lineKeysOf(raws: string[]): string[] {
  const seen = new Map<string, number>()

  return raws.map((raw) => {
    const nth = seen.get(raw) ?? 0
    seen.set(raw, nth + 1)
    return `${nth}:${raw}`
  })
}
