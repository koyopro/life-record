/**
 * 手元の控えと突き合わせる取得の応答（docs/15-client-state.md 14.2 の 4）。
 *
 * 取得（GET）と保存（PATCH / PUT）は別々に飛ぶので、**保存より前に出した取得の
 * 応答が保存の後で届く**ことがある。その内容にはこちらの保存が入っていないため、
 * そのまま当てると書いたそばから巻き戻る。
 *
 * どちらが新しいかを受け取る側が判断できるよう、**サーバーが応答を作った時刻**を
 * 必ず添える。包みの形を1つに決めておくと、時刻を持たない応答をうっかり
 * 重ねてしまうことがない（重ねる側は `fetchedAt` を必須で受け取る）。
 *
 * 作るのは `server/utils/fetched.ts` の `fetched()` だけ。時刻は**読む前**に
 * 打つ決まりで、そこを間違えないようにするため。
 */
export interface Fetched<T> {
  /** サーバーがこの応答を作った時刻（ISO 8601）。 */
  fetchedAt: string
  data: T
}
